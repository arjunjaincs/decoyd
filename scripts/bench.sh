#!/usr/bin/env bash
# scripts/bench.sh — Run watch-package benchmarks and generate docs/BENCHMARKS.md
#
# Usage: bash scripts/bench.sh
# Output: docs/BENCHMARKS.md (requires a [RAN] run to get real numbers)
#
# Note: This script must be run on Linux with Go installed.
# Tier 1 numbers require sudo and fanotify support (kernel >= 5.1).

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$REPO_ROOT/docs/BENCHMARKS.md"
BENCH_ARGS="-bench=. -benchtime=5s -benchmem -count=3"

echo "Running benchmarks..." >&2

TIER2_OUT="$(cd "$REPO_ROOT" && go test $BENCH_ARGS ./internal/watch/ 2>&1)"
echo "$TIER2_OUT" >&2

cat > "$OUT" <<'MDEOF'
# Decoyd Benchmarks

> **Status**: This file was generated by `scripts/bench.sh`.
> Numbers marked [RAN] were measured on the system where the script was run.
> Numbers marked UNKNOWN have not been measured.

## Test Environment

MDEOF

echo "- OS: $(uname -sr)" >> "$OUT"
echo "- CPU: $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2 | xargs)" >> "$OUT"
echo "- Go: $(go version)" >> "$OUT"
echo "- Date: $(date -u +%Y-%m-%dT%H:%M:%SZ)" >> "$OUT"
echo "" >> "$OUT"

cat >> "$OUT" <<'MDEOF'
## Tier 2 (inotify/fsnotify) Latency [RAN]

Time from file open to event receipt in the watcher callback.

MDEOF

echo "\`\`\`" >> "$OUT"
echo "$TIER2_OUT" >> "$OUT"
echo "\`\`\`" >> "$OUT"

cat >> "$OUT" <<'MDEOF'

## Tier 1 (fanotify) Latency

> UNKNOWN — requires Linux + sudo + fanotify support (kernel >= 5.1).
> Run with: `sudo -E go test -bench=BenchmarkFanotify -benchtime=5s -tags privileged ./internal/watch/`

## Idle Resource Usage

Approximate RSS overhead with 100 watched files:
- Measured via `-benchmem` output above (see allocs/op column)
- CPU usage: UNKNOWN (requires `perf stat` or equivalent)

## False-Positive Analysis

| Scenario | Expected | Decoyd Response |
|----------|----------|-----------------|
| User reads their own `.npmrc` | True positive (intentional decoy) | Alert fires |
| Backup agent reads all home files | False positive risk | Add process to exclusion list |
| Security scanner | False positive risk | Use `decoyd events` to review |
| IDE language server reads project files | False positive risk | Decoys should be outside project dirs |

MDEOF

echo "Written: $OUT" >&2
